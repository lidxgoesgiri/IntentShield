/**
 * Generates the landing simulator's controlled fixtures (PRD §28.3).
 *
 * The bytes are produced by the PRODUCTION builder from transparent,
 * SHA-256-derived sample parties, then written as base64 so the landing page
 * does not need to ship the transaction builder. A unit test re-derives them
 * and fails if the committed file drifts from the real builder output.
 *
 * Usage: npx tsx scripts/generate-demo-fixtures.ts
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { getBase64Decoder, type Address } from "@solana/kit";
import { deriveDemoParties } from "../src/features/demo/lib/fixture-derivation";
import { buildNativeSolTransfer } from "../src/features/transfer/lib/build-transfer";

export function buildLandingFixtures() {
  const parties = deriveDemoParties();
  const lifetime = { blockhash: parties.blockhash, lastValidBlockHeight: 0n };
  const encode = (bytes: Uint8Array) => getBase64Decoder().decode(bytes);
  const build = (recipient: string, amount: bigint) =>
    encode(
      buildNativeSolTransfer(
        { sender: parties.sender as Address, recipient: recipient as Address, amountLamports: amount },
        lifetime,
        { now: 0 },
      ).messageBytes,
    );
  return {
    parties,
    messages: {
      exactMatch: build(parties.recipient, 100_000_000n),
      changedAmount: build(parties.recipient, 800_000_000n),
      changedRecipient: build(parties.lookalikeRecipient, 100_000_000n),
    },
  };
}

function main() {
  const { parties, messages } = buildLandingFixtures();
  const file = `// AUTO-GENERATED by scripts/generate-demo-fixtures.ts — do not edit by hand.
// Controlled DEMO fixtures: synthetic parties (base58(SHA-256("intentshield:demo:<label>")),
// no known private keys) and unsigned messages compiled by the production builder.
// Never signed, never broadcast, not on-chain data.

export const DEMO_PARTIES = {
  sender: "${parties.sender}",
  recipient: "${parties.recipient}",
  lookalikeRecipient: "${parties.lookalikeRecipient}",
  blockhash: "${parties.blockhash}",
} as const;

export const DEMO_MESSAGES_BASE64 = {
  exactMatch: "${messages.exactMatch}",
  changedAmount: "${messages.changedAmount}",
  changedRecipient: "${messages.changedRecipient}",
} as const;
`;
  const target = join(process.cwd(), "src", "features", "landing", "simulator", "demo-fixtures.generated.ts");
  writeFileSync(target, file);
  console.log(`Wrote ${target}`);
}

if (process.argv[1] && process.argv[1].endsWith("generate-demo-fixtures.ts")) main();
